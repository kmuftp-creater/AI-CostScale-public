-- 講清楚 actual_twd 是「本金＋國外交易服務費」（2026-09-22，待辦 C13）
--
-- 起因：這一欄原本的註解只寫「信用卡帳單上的實際入帳台幣金額，人工填」，
-- 沒有回答**帳單上有兩行的時候該填哪個**：
--     08/06  ANTHROPIC* CLAUDE SUB   USD 100   TWD 3,233
--     08/06  國外交易服務費                     TWD    48
-- User 很自然地填了金額大的那一行（3,233）。於是所有反推出來的溢價
-- 整批少了 1.5%，而我拿那批數字下結論說「這張卡幾乎沒有海外手續費、
-- fx_markup_pct = 1.5 沒有資料支持」——**結論完全錯誤，而且看不出哪裡錯**，
-- 因為每一個數字本身都是對的。
--
-- 定義沒寫下來，填的人用常識填，而兩個人的常識不一樣。
-- 這一欄要跟 amount_twd 比對才有意義，所以它必須與 amount_twd 同一個口徑：
--     amount_twd = fee ×(1+tax_pct/100)× fx_rate ×(1+markup_pct/100)
-- 右邊最後那個 (1+markup_pct/100) 就是國外交易服務費，
-- 所以 actual_twd 也必須含它，否則兩邊比的不是同一件事。
--
-- 這支 migration 只改註解，不動任何資料。

COMMENT ON COLUMN costscale.subscription_charges.actual_twd IS
  '信用卡帳單上這筆交易實際扣走的台幣**總額**，人工填。NULL 表示尚未對帳。'
  '**帳單上是兩行的話要相加**：消費本金那一行 ＋ 緊接著的「國外交易服務費」那一行。'
  '只填本金會讓反推出來的溢價整批少一個 markup_pct（2026-09-21 踩過，而且據此下了錯誤結論）。'
  '口徑要與 amount_twd 一致——amount_twd 本身就含 markup_pct，兩邊不同口徑就不是在比同一件事。';
