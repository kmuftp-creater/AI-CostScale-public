-- 訂閱的複查日（2026-09-21）
--
-- 起因（User，2026-09-21）：Claude 這次從 5x 升到 20x 是**臨時的一期**，
-- 10/21 續約時要降回 5x。也就是月費必須在 10/20 收工前改回 100——
-- 排程每天 05:20 在扣款日當天用**那一刻的 fee** 凍結，
-- 10/21 早上一到就會凍成 US$210 而不是 US$105。
--
-- 而自動凍結的那一筆**介面上刪不掉**（只有 source='manual' 能刪，
-- 見 lib/db.ts 的 deleteManualCharge）。凍錯了只能進資料庫改。
-- 所以這是一個「忘記一次就要開資料庫收拾」的日期，不能靠備註欄和記性。
--
-- `costscale.apps` 早就有同名欄位與提醒（db/init/10），理由一模一樣：
-- 「現在自用、開賣後必須關掉訂閱」。訂閱表反而沒有，這次補上，
-- 走的是 listReminders 既有的那條路，不另外做一套提醒。
--
-- 為什麼不做成「自動在某天把 fee 改回去」：那等於讓系統在沒有人看的時候
-- 改動金額，而金額改錯的代價是帳目錯而且不會有人發現。
-- 提醒人去改，錯了看得見；自動改，錯了看不見。

ALTER TABLE costscale.subscriptions
  ADD COLUMN IF NOT EXISTS review_at DATE;

COMMENT ON COLUMN costscale.subscriptions.review_at IS
  '這筆訂閱要回來檢查一次的日期（降級、退訂、方案到期）。到期前會出現在提醒清單。'
  '臨時升級一定要設：排程在扣款日當天用當下的 fee 凍結，改晚了就會凍成錯的金額，而自動凍的那筆刪不掉。';
